export function marketplaceProductById(id: string) {
  return MARKETPLACE_CATALOG.find((item) => item.id === id);
}

export function museMarketplaceProducts(): MuseGarment[] {
  return MARKETPLACE_CATALOG.filter((item) => item.in_stock).map((item) => ({
    id: item.id,
    name: item.name,
    category: item.category,
    subcategory: item.subcategory,
    colors: item.colors,
    formality: item.formality,
    style_tags: item.style_tags,
    price: item.price,
    currency: item.currency,
    sizes: item.sizes,
    brand: item.brand,
    in_stock: item.in_stock,
    source: 'marketplace',
    temperature_range_c: item.temperature_range_c,
    image_url: item.image_url,
  }));
}
